"""Types of the S30 persistent vars the dedi's pdef lacks, for the S30 client bridge.

The S30 client reads persistent vars the dedi's pdef does not have (S30-only structs past
the dedi's caps); bridge_persistence_s30 answers those reads itself. GetPersistentVar must
push the var's own type (0xC34750: 0 bool, 1 int, 2 float, 3 string, 4 enum by name), or
a script that does `expect bool( player.GetPersistentVar( ... ) )` stops. This flattens
both pdefs to leaf paths (array indices as "[]", the form the bridge normalizes names to)
and writes the S30 leaves the dedi lacks, with their S30 type, as a sorted C table.

usage: pdef_missing_types.py <S30 persistent_player_data.pdef> <dedi persistent_player_data.pdef> <out .h>
       (each base file's pdef_autogen.pdef is read from next to it)
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pdef_count  # noqa: E402

TYPE_CODE = {"bool": 0, "int": 1, "float": 2}


def leaves(base):
	enums, structs, top = pdef_count.load(base, os.path.join(os.path.dirname(base), "pdef_autogen.pdef"))
	out = {}

	def walk(decls, prefix, depth):
		if depth > 16:
			raise SystemExit("struct nesting too deep at " + prefix)
		for d in decls:
			typ, rest = d.split(None, 1)
			name = re.split(r"[\[\s]", rest.strip(), 1)[0]
			dims = len(re.findall(r"\[[^\]]+\]", rest))
			path = prefix + name + "[]" * dims
			if typ in structs:
				walk(structs[typ], path + ".", depth + 1)
			elif typ in TYPE_CODE:
				out[path] = TYPE_CODE[typ]
			elif typ.startswith("string"):
				out[path] = 3
			elif typ in enums:
				out[path] = 4
			else:
				raise SystemExit("unknown pdef type %s (%s)" % (typ, d))

	walk(top, "", 0)
	return out


def main(s30_base, dedi_base, out_path):
	s30 = leaves(s30_base)
	dedi = leaves(dedi_base)
	missing = sorted((p, t) for p, t in s30.items() if p not in dedi)
	lines = [
		"// Generated by s30/tools/pdef_missing_types.py -- do not edit.",
		"// S30 persistent vars the dedi's pdef lacks, with their S30 type (0 bool, 1 int,",
		"// 2 float, 3 string, 4 enum); array indices are \"[]\". Sorted for binary search.",
		"#pragma once",
		"#include <cstdint>",
		"",
		"struct PdefMissingType_t { const char* pszPath; uint8_t nType; };",
		"",
		"inline constexpr PdefMissingType_t kPdefMissingTypes[] = {",
	]
	lines += ['\t{ "%s", %d },' % (p, t) for p, t in missing]
	lines += ["};", ""]
	open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
	counts = [sum(1 for _, t in missing if t == k) for k in range(5)]
	print("S30 leaves %d, dedi leaves %d, missing on the dedi %d (bool %d, int %d, float %d, string %d, enum %d)"
		% (len(s30), len(dedi), len(missing), *counts))


if __name__ == "__main__":
	if len(sys.argv) != 4:
		sys.exit(__doc__)
	main(*sys.argv[1:])
