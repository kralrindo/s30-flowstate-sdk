"""Per-weapon mod index remap, S3 dedi -> S30.1 client (s30/docs/20).

A weapon's mod index is the position of the mod in its "Mods" block: the dedi reads
build/s3_server/platform/scripts/weapons/<weapon>.txt (S3 engine, at most 32 mods,
server-only mods trimmed by loot_weapon_mods.py), the S30 client its weapon settings
asset (exported to asset_pipeline/weapons_s30/weapon/<weapon>.txt, same order). The
dedi sends m_modBitfield* as one 32-bit mask in its own indices; S30 reads three
dwords (96 bits) in its indices. This writes the name-matched map.

usage: py weapon_mod_remap.py <dedi weapons dir> <S30 weapons dir> <out.h> [<out.tsv>]
"""
import os
import re
import sys

TOKEN = re.compile(r'"((?:[^"\\]|\\.)*)"|([{}])|//[^\n]*|([^\s{}"]+)')


def tokens(text):
	for m in TOKEN.finditer(text):
		if m.group(1) is not None:
			yield m.group(1)
		elif m.group(2) is not None:
			yield m.group(2)
		elif m.group(3) is not None:
			yield m.group(3)


def mod_names(path):
	"""Ordered top-level keys of WeaponData/Mods, or None when there is no Mods block."""
	toks = list(tokens(open(path, encoding="utf-8", errors="replace").read()))
	depth = 0
	i = 0
	while i < len(toks):
		t = toks[i]
		if t == "{":
			depth += 1
		elif t == "}":
			depth -= 1
		elif depth == 1 and t == "Mods" and i + 1 < len(toks) and toks[i + 1] == "{":
			names = []
			j = i + 2
			d = 1
			while j < len(toks) and d > 0:
				u = toks[j]
				if u == "{":
					d += 1
				elif u == "}":
					d -= 1
				elif d == 1 and j + 1 < len(toks) and toks[j + 1] == "{":
					names.append(u)
				j += 1
			return names
		i += 1
	return None


def main():
	if len(sys.argv) < 4:
		sys.exit(__doc__)
	dedi_dir, s30_dir, out_h = sys.argv[1:4]
	out_tsv = sys.argv[4] if len(sys.argv) > 4 else None
	rows = []
	stats = {"weapons": 0, "identity": 0, "remapped": 0, "no_s30": 0, "unmatched_mods": 0, "s30_over_96": 0}
	for fn in sorted(os.listdir(dedi_dir)):
		if not fn.endswith(".txt"):
			continue
		dedi = mod_names(os.path.join(dedi_dir, fn))
		if not dedi:
			continue
		stats["weapons"] += 1
		s30_path = os.path.join(s30_dir, fn)
		if not os.path.exists(s30_path):
			stats["no_s30"] += 1
			rows.append((fn[:-4], dedi, None))
			continue
		s30 = mod_names(s30_path) or []
		if len(s30) > 96:
			stats["s30_over_96"] += 1
		index = {n.lower(): k for k, n in enumerate(s30)}
		remap = [index.get(n.lower(), -1) for n in dedi]
		stats["unmatched_mods"] += sum(1 for r in remap if r < 0)
		if remap == list(range(len(dedi))):
			stats["identity"] += 1
		else:
			stats["remapped"] += 1
		rows.append((fn[:-4], dedi, (s30, remap)))

	with open(out_h, "w", encoding="utf-8", newline="\n") as f:
		f.write("// Generated by s30/tools/weapon_mod_remap.py -- do not edit.\n")
		f.write("// Per weapon: dedi mod index (its scripts/weapons Mods order) -> S30.1 mod index\n")
		f.write("// (S30 weapon settings order), -1 = no S30 mod of that name. s30/docs/20.\n")
		f.write("#pragma once\n#include <cstdint>\n\n")
		f.write("struct WeaponModRemap_t { const char* pszWeapon; int nMods; int8_t nS30[32]; };\n\n")
		f.write("inline constexpr WeaponModRemap_t kWeaponModRemap[] = {\n")
		for name, dedi, s30 in rows:
			if s30 is None:
				continue
			remap = s30[1][:32]
			if remap == list(range(len(remap))):
				continue  # identity: no entry, the proxy passes the mask through
			vals = ", ".join(str(v) for v in remap)
			f.write('\t{ "%s", %d, { %s } },\n' % (name, len(remap), vals))
		f.write("};\n")
	if out_tsv:
		with open(out_tsv, "w", encoding="utf-8", newline="\n") as f:
			f.write("weapon\tdedi_index\tmod\ts30_index\n")
			for name, dedi, s30 in rows:
				for k, n in enumerate(dedi):
					f.write("%s\t%d\t%s\t%s\n" % (name, k, n, "no_s30_weapon" if s30 is None else s30[1][k]))
	print(stats)


if __name__ == "__main__":
	main()
