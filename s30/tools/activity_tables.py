"""Generates src/core_s30/activity_s3_to_s30_table.h.

Inputs (from activity_list.py, verified: on the S21 client it reproduces the
SDK's embedded activity_s21_enum.h exactly):
  s3_engine.tsv   S3 dedi engine table (r5apex_ds.exe RegisterSharedActivities 0xB38FC0)
  s21_engine.tsv  S21 client table (0x9DA060)
  s30_engine.tsv  S30.1 client table (0xAA11C0; RegisterActivity 0xAA0F00 has no other caller)
  activity_types.txt  the dedi's custom activities, appended after the engine table the
                  way the dedi SDK's LoadCustomActivitiesFromFile does (activity.cpp): file
                  order, `//` comments stripped, ACT_ names only, engine and in-file
                  duplicates skipped, id = previous max + 1.

usage: py activity_tables.py <analysis/activity dir> <dedi activity_types.txt> <out .h>
"""
import os
import sys


def load(path):
	rows = []
	for line in open(path, encoding='latin1'):
		i, n = line.rstrip('\n').split('\t')
		rows.append((int(i), n))
	return rows


def dedi_customs(path, engine):
	names = {n for _, n in engine}
	nxt = max(i for i, _ in engine) + 1
	out, seen = [], set()
	for raw in open(path, encoding='latin1'):
		s = raw.strip()
		if not s or s.startswith('//'):
			continue
		s = s.split('//')[0].strip()
		if not s or not s.startswith('ACT_'):
			continue
		if s in seen or s in names:
			continue
		seen.add(s)
		out.append((nxt, s))
		nxt += 1
	return out


def main():
	if len(sys.argv) != 4:
		sys.exit(__doc__)
	d = sys.argv[1]
	s3e = load(os.path.join(d, 's3_engine.tsv'))
	s21 = load(os.path.join(d, 's21_engine.tsv'))
	s30 = load(os.path.join(d, 's30_engine.tsv'))
	cust = dedi_customs(sys.argv[2], s3e)
	s3 = s3e + cust
	s30_by_name = {n: i for i, n in s30}
	for lst, what in ((s3, 'S3'), (s21, 'S21'), (s30, 'S30')):
		ids = [i for i, _ in lst]
		assert ids == list(range(len(ids))), what + ' ids not dense'
		assert len({n for _, n in lst}) == len(lst), what + ' duplicate names'

	def table(src):
		return [s30_by_name.get(n, -1) for _, n in src]

	t3 = table(s3)
	t21 = table(s21)
	s3_names = {n for _, n in s3}
	s30_only = [(i, n) for i, n in s30 if n not in s3_names]
	L = []
	L.append("//=============================================================================//")
	L.append("//")
	L.append("// Purpose: activity ids, S3 dedi / S21 -> S30.1 client, matched by name.")
	L.append("// Generated by s30/tools/activity_tables.py -- do not hand-edit (s30/docs/14).")
	L.append("//")
	L.append("// Activity ids are positions in each engine's RegisterSharedActivities table.")
	L.append("// S3: r5apex_ds.exe 0xB38FC0 (ids 0..%d) + %d customs from the dedi's" % (len(s3e) - 1, len(cust)))
	L.append("//     scripts/activity_types.txt (ids %d..%d, file order)." % (len(s3e), len(s3) - 1))
	L.append("// S21: r5apex_dx12 S21 0x9DA060 (ids 0..%d). S30.1: 0xAA11C0 (ids 0..%d, no custom file)." % (len(s21) - 1, len(s30) - 1))
	L.append("// -1: the activity has no S30 counterpart.")
	L.append("//")
	L.append("//=============================================================================//")
	L.append("#ifndef CORE_S30_ACTIVITY_S3_TO_S30_TABLE_H")
	L.append("#define CORE_S30_ACTIVITY_S3_TO_S30_TABLE_H")
	L.append("")
	L.append("struct S30ActivityEntry_t { const char* pszName; int nId; };")
	L.append("")
	L.append("// The S30.1 client's activity table (ACT_RESET, id 0, left out as in activity_s21_enum.h).")
	L.append("inline constexpr S30ActivityEntry_t kS30Activities[] = {")
	for i, n in s30:
		if i:
			L.append('\t{ "%s", %d },' % (n, i))
	L.append("};")
	L.append("inline constexpr int kS30ActivityCount = sizeof(kS30Activities) / sizeof(kS30Activities[0]);")
	L.append("")
	L.append("// S3 dedi activity id (engine + activity_types.txt) -> S30 id.")
	L.append("inline constexpr short kActS3ToS30[%d] = {" % len(t3))
	for (i, n), v in zip(s3, t3):
		L.append("\t%5d, // %4d %s" % (v, i, n))
	L.append("};")
	L.append("")
	L.append("// S21 activity id -> S30 id (what the dedi's S3->S21 wire proxies produce today).")
	L.append("inline constexpr short kActS21ToS30[%d] = {" % len(t21))
	for (i, n), v in zip(s21, t21):
		L.append("\t%5d, // %4d %s" % (v, i, n))
	L.append("};")
	L.append("")
	s3_by_name = {n: i for i, n in s3}
	t30 = [s3_by_name.get(n, -1) for _, n in s30]
	L.append("// S30 activity id -> S3 dedi id (usercmd weaponCustomActivity, client to dedi).")
	L.append("inline constexpr short kActS30ToS3[%d] = {" % len(t30))
	for (i, n), v in zip(s30, t30):
		L.append("	%5d, // %4d %s" % (v, i, n))
	L.append("};")
	L.append("")
	L.append("// Values the S30 client writes into the player's queued activity itself")
	L.append("// (0x6176D0, player+0x209A); a queued-activity translation must leave them alone.")
	L.append("inline constexpr short kS30LocalQueuedActivities[] = { 718, 719, 746, 754, 781, 782, 783, 829, 843, 844, 845 };")
	L.append("")
	L.append("#endif // CORE_S30_ACTIVITY_S3_TO_S30_TABLE_H")
	open(sys.argv[3], 'w', newline='\n').write("\n".join(L) + "\n")
	print("S3 %d (engine %d + custom %d): %d mapped, %d without S30" % (len(s3), len(s3e), len(cust), sum(v >= 0 for v in t3), sum(v < 0 for v in t3)))
	print("S21 %d: %d mapped, %d without S30" % (len(s21), sum(v >= 0 for v in t21), sum(v < 0 for v in t21)))
	print("S30 %d: %d have no S3 source" % (len(s30), len(s30_only)))
	print("S3 without S30:", [n for (i, n), v in zip(s3, t3) if v < 0])
	print("S21 without S30:", [n for (i, n), v in zip(s21, t21) if v < 0])


if __name__ == "__main__":
	main()
