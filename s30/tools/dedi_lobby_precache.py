"""Make the S3 dedi precache the models the S30 client's lobby menus create.

The S30 client creates client-side props in the lobby (character select, store, menu
backgrounds) whose model index must be in the server's model precache; S30's own server
precaches them, the dedi's S21-era scripts do not, and the client stops with "Failed to
find model index ... Make sure it is precached" (a client script error drops the
connection). This collects every $"mdl/...rmdl" literal from the S30 lobby/menu client
scripts, keeps those the dedi's paks contain (built_*.csv inventories: a model the dedi
cannot load stops it with a modal error), and writes them into a marked block of the
dedi's SERVER-only MenuModels_Init (sh_menu_models.gnut, run by Server_Lobby_Init).
The first run keeps the original as sh_menu_models.gnut.s21; reruns replace the block.

usage: py dedi_lobby_precache.py <S30 client vscripts dir> <dedi inv dir> <dedi platform dir>
"""
import csv
import glob
import os
import re
import shutil
import sys

SCRIPTS = ["sh_menu_models.gnut.client", "sh_character_select.gnut.client"]
SCRIPT_GLOBS = ["*lobby*.client", "client/*lobby*.client", "lobby/*.client"]
BEGIN = "// [S30 lobby precache] begin -- generated by s30/tools/dedi_lobby_precache.py"
END = "// [S30 lobby precache] end"
MODEL_RE = re.compile(rb'\$"(mdl/[^"]+\.rmdl)"')


def norm(path):
	return path.replace("\\", "/").lower()


def main():
	if len(sys.argv) != 4:
		sys.exit(__doc__)
	scripts_dir, inv_dir, platform = sys.argv[1:]
	files = [os.path.join(scripts_dir, s) for s in SCRIPTS]
	for g in SCRIPT_GLOBS:
		files += glob.glob(os.path.join(scripts_dir, g))
	wanted = set()
	for f in sorted(set(files)):
		if os.path.isfile(f):
			wanted.update(m.group(1).decode() for m in MODEL_RE.finditer(open(f, "rb").read()))
	have = set()
	for c in glob.glob(os.path.join(inv_dir, "built_*.csv")):
		for row in csv.DictReader(open(c, newline="", encoding="utf-8", errors="replace")):
			if row.get("type") == "mdl_":
				have.add(norm(row["asset_name"]))
	models = sorted(m for m in wanted if norm(m) in have)
	missing = sorted(m for m in wanted if norm(m) not in have)
	if not have:
		sys.exit("no models in %s/built_*.csv -- refusing" % inv_dir)

	path = os.path.join(platform, "scripts", "vscripts", "sh_menu_models.gnut")
	if not os.path.exists(path + ".s21"):
		shutil.copyfile(path, path + ".s21")
	data = open(path, "rb").read()
	nl = b"\r\n" if b"\r\n" in data else b"\n"
	data = re.sub(re.escape(BEGIN.encode()) + rb".*?" + re.escape(END.encode()) + rb"\r?\n", b"", data, flags=re.S)
	anchor = b"void function MenuModels_Init()"
	i = data.find(anchor)
	if i < 0 or data.find(anchor, i + 1) >= 0:
		sys.exit("MenuModels_Init not found exactly once in %s" % path)
	brace = data.index(b"{", i) + 1
	eol = data.index(b"\n", brace) + 1
	block = [BEGIN] + ['\tPrecacheModel( $"%s" )' % m for m in models] + [END]
	data = data[:eol] + nl.join(s.encode() for s in block) + nl + data[eol:]
	open(path, "wb").write(data)
	print("%s: %d lobby models precached, %d not in the dedi's paks (left out)" % (path, len(models), len(missing)))
	for m in missing:
		print("  not in dedi paks:", m)


if __name__ == "__main__":
	main()
